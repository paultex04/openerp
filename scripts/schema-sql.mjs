/**
 * Regenerates `server/prisma/schema.sql`, or proves it is still current.
 *
 * ## What that file is
 *
 * The whole schema, as one SQL script, for creating a database that does not
 * exist yet. `server/prisma/schema.prisma` remains the schema; this is what the
 * Prisma CLI emits for it, and it is the same diff `prisma db push` applies.
 *
 * ## Why it is committed rather than generated during the image build
 *
 * `prisma migrate diff` needs the Prisma CLI, and the API runtime image installs
 * with `--omit=dev`, so it does not have it. Generating the file during the build
 * would put a network-dependent step that cannot be tested locally between a push
 * and a deploy. A committed file is reviewable, has no build-time dependency, and
 * can be applied with `psql` if the migration runner is ever unavailable.
 *
 * ## The drift this prevents
 *
 * Two sources of truth for one schema is the failure this script exists to make
 * impossible. `--check` compares the committed file against a fresh emission, so
 * editing `schema.prisma` without regenerating is caught by `npm run verify`
 * rather than by a deployment that comes up on an old schema and only fails when
 * a route touches the missing column.
 *
 * Usage:
 *   node scripts/schema-sql.mjs            rewrite the generated portion
 *   node scripts/schema-sql.mjs --check    exit non-zero if it is out of date
 *
 * The prose header at the top of the file is preserved; everything from the first
 * `CREATE SCHEMA` onwards is generated and is not to be edited.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const serverDir = resolve(repoRoot, 'server');
const schemaPath = resolve(serverDir, 'prisma', 'schema.prisma');
const configPath = resolve(serverDir, 'prisma.config.ts');
const outPath = resolve(serverDir, 'prisma', 'schema.sql');

// Prisma's script always opens with this statement, so it is an unambiguous
// boundary between the prose header and the generated body.
const MARKER = 'CREATE SCHEMA';

const check = process.argv.includes('--check');
const toLf = (text) => text.replace(/\r\n/g, '\n');

function emit() {
  const result = spawnSync(
    'npx',
    [
      'prisma',
      'migrate',
      'diff',
      '--from-empty',
      '--to-schema',
      schemaPath,
      '--script',
      '--config',
      configPath,
    ],
    {
      cwd: serverDir,
      encoding: 'utf8',
      // `npx` is a shell builtin on Windows; on POSIX it resolves directly.
      shell: process.platform === 'win32',
      // A diff from an empty schema to a datamodel never opens a connection, but
      // loading `prisma.config.ts` asks for DATABASE_URL. The placeholder keeps
      // this runnable in a checkout with no `.env`, which is the case CI is in.
      env: {
        ...process.env,
        DATABASE_URL:
          process.env.DATABASE_URL ??
          'postgresql://unused:unused@127.0.0.1:5432/unused?schema=public',
      },
    },
  );

  if (result.status !== 0) {
    console.error(result.stderr?.trim() || 'prisma migrate diff failed with no output');
    process.exit(result.status ?? 1);
  }

  const sql = toLf(result.stdout);
  const index = sql.indexOf(MARKER);
  if (index === -1) {
    console.error(`prisma migrate diff emitted no ${MARKER} statement; refusing to write it.`);
    process.exit(1);
  }
  return sql.slice(index);
}

function split(text) {
  const index = text.indexOf(MARKER);
  return {
    header: index === -1 ? '' : text.slice(0, index),
    body: index === -1 ? text : text.slice(index),
  };
}

const generatedBody = emit();
const existing = existsSync(outPath) ? split(toLf(readFileSync(outPath, 'utf8'))) : null;

if (check) {
  if (!existing) {
    console.error('server/prisma/schema.sql is missing. Run: npm run db:schema:write');
    process.exit(1);
  }
  if (existing.body !== generatedBody) {
    console.error('server/prisma/schema.sql is out of date with server/prisma/schema.prisma.');
    console.error('Run: npm run db:schema:write, then commit the result.');
    process.exit(1);
  }
  console.log('server/prisma/schema.sql matches server/prisma/schema.prisma');
  process.exit(0);
}

const header = existing?.header ?? '-- Generated by scripts/schema-sql.mjs.\n\n';
writeFileSync(outPath, `${header}${generatedBody}`, 'utf8');
console.log(`Wrote ${outPath}`);
